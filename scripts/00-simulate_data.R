#### Workspace setup ####

set.seed(924)

#### Simulate variables of interest ####

### Building Properties ###

n_building <- 3500

# Building ID: unique to each building; repeated evaluations on the same building
# has the same building ID but will appear in different rows.

building_id <- seq_len(n_building)

# Building evaluation year: ranges from 2023-2025; the proportion of buildings being
# evaluated each year is an approximate to the original data.

evaluation_year <- sample (2023:2025, n_building, replace = TRUE,
                           prob = c(0.1, 0.5, 0.4))

# Building built year: to ensure building age stays non-negative, we assume all
# buildings were built before 2023; in the real data, there will be buildings built
# after 2022, but the actual age is always non-negative.

year_built <- sample(1900:2022, n_building, replace = TRUE)

# Property type: categorical variable with three levels "Private", "Social Housing",  
# and "TCHC"; the proportion of property type is an approximate to the original data.

property_type <- sample(c("Private", "Social Housing", "TCHC"), n_building, 
                        replace = TRUE, prob = c(0.84, 0.07, 0.09))

# Building confirmed units: I manually chose a size band and assigned proportion
# to each size group; this proportion is to roughly approximate the right-skewed
# distribution of the original dataset.
# Generated by ChatGPT (GPT-6 Sol), OpenAI, September 24, 2026. 

unit_ranges <- list(10:19, 20:49, 50:99, 100:199, 200:399, 400:800)
unit_band <- sample(seq_along(unit_ranges), n_building, replace = TRUE,
                    prob = c(0.208, 0.286, 0.192, 0.177, 0.122, 0.015))
confirmed_units <- vapply(unit_band, function(i) sample(unit_ranges[[i]], 1L),
                          integer(1))


### Log Evaluation Scores ###

# I use the approximate probability distribution from the original dataset to 
# simulate the evaluation scores for each log.
# Score 2 means N/A; 0 has no published meaning; only score 1 and 3 have practical
# values. 

score_probs <- list(
  tenant = c(0.017, 0.1, 0.027, 0.855),
  pest = c(0.019, 0.114, 0.032, 0.836),
  maintenance = c(0.019, 0.128, 0.026, 0.827))
log_columns <- c("TENANT SERVICE REQUEST LOG", "PEST CONTROL LOG",
                 "MAINTENANCE LOG")


#### Simulate Data Frame ####

simulated <- data.frame(
  "RSN" = building_id, "CONFIRMED UNITS" = confirmed_units,
  "YEAR BUILT" = year_built, "YEAR EVALUATED" = evaluation_year,
  "PROPERTY TYPE" = property_type,
  "TENANT SERVICE REQUEST LOG" = sample(0:3, n_building, replace = TRUE,
                                        prob = score_probs$tenant),
  "PEST CONTROL LOG" = sample(0:3, n_building, replace = TRUE,
                              prob = score_probs$pest),
  "MAINTENANCE LOG" = sample(0:3, n_building, replace = TRUE,
                             prob = score_probs$maintenance),
  check.names = FALSE
)

# Account for repetitive evaluation of the same building.

n_evaluation <- 5300
repeated <- sample(which(evaluation_year > 2023), n_evaluation - n_building)
earlier <- simulated[repeated, ]
earlier[["YEAR EVALUATED"]] <- earlier[["YEAR EVALUATED"]] - 1
earlier[["TENANT SERVICE REQUEST LOG"]] <- sample(0:3, nrow(earlier), 
                                                   replace = TRUE, 
                                                   prob = score_probs$tenant)
earlier[["PEST CONTROL LOG"]] <- sample(0:3, nrow(earlier), replace = TRUE, 
                                        prob = score_probs$pest)
earlier[["MAINTENANCE LOG"]] <- sample(0:3, nrow(earlier), replace = TRUE, 
                                       prob = score_probs$maintenance)
simulated <- rbind(simulated, earlier)
simulated <- simulated[sample(nrow(simulated)), ] ## Shuffle the new set
row.names(simulated) <- NULL


#### Testing ####

### Keep the latest evaluation for each building

sorted <- simulated[order(simulated$RSN, -simulated[["YEAR EVALUATED"]]), ]
latest <- sorted[!duplicated(sorted$RSN), ]
row.names(latest) <- NULL

# Check unique row for each buildling

stopifnot(nrow(latest) == length(unique(simulated$RSN)))

# Create derived variable, building age: it stores the age of the building when 
# the latest evaluation took place, rather than the current time.

latest[["BUILDING AGE"]] <- latest[["YEAR EVALUATED"]] - latest[["YEAR BUILT"]]

# Create derived variable, building size: it divides buildings into four groups
# based on confirmed units
# Generated by ChatGPT (GPT-6 Sol), OpenAI, September 24, 2026. 

size_breaks <- quantile(latest[["CONFIRMED UNITS"]],
                        probs = c(0, 0.25, 0.50, 0.75, 1))
latest$building_size <- cut(latest[["CONFIRMED UNITS"]], breaks = size_breaks, 
                         include.lowest = TRUE,
                         labels = c("Small", "Medium", "Large", "Very Large"))
table(latest$building_size) ## Check number of buildings in each group

#### Save data ####
write_csv(latest, "data/00-simulated_data/simulated_data.csv")
